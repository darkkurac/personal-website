const languageButtons = document.querySelectorAll(".language-button");
const textElements = document.querySelectorAll("[data-i18n]");
const altElements = document.querySelectorAll("[data-i18n-alt]");
const ariaElements = document.querySelectorAll("[data-i18n-aria]");
const menuButton = document.querySelector(".menu-button");
const themeButton = document.querySelector(".theme-button");
const themeButtonIcon = document.querySelector(".theme-button-icon");
const mainNav = document.querySelector(".main-nav");
const navLinks = document.querySelectorAll(".main-nav a");

let currentLanguage = "ru";
let currentTheme = "dark";

function setLanguage(language) {
  currentLanguage = language;
  const dictionary = translations[language];

  document.documentElement.lang = language;
  document.title = dictionary.pageTitle;

  textElements.forEach((element) => {
    const key = element.dataset.i18n;
    element.textContent = dictionary[key];
  });

  altElements.forEach((element) => {
    const key = element.dataset.i18nAlt;
    element.alt = dictionary[key];
  });

  ariaElements.forEach((element) => {
    const key = element.dataset.i18nAria;
    element.setAttribute("aria-label", dictionary[key]);
  });

  languageButtons.forEach((button) => {
    button.classList.toggle("is-active", button.dataset.lang === language);
  });

  updateMenuLabel();
  updateThemeLabel();
}

function setTheme(theme) {
  currentTheme = theme;
  document.body.dataset.theme = theme;
  updateThemeLabel();
}

function closeMenu() {
  document.body.classList.remove("is-menu-open");
  mainNav.classList.remove("is-open");
  menuButton.setAttribute("aria-expanded", "false");
  updateMenuLabel();
}

function updateMenuLabel() {
  const dictionary = translations[currentLanguage];
  const isOpen = mainNav.classList.contains("is-open");
  menuButton.setAttribute("aria-label", isOpen ? dictionary.menuClose : dictionary.menuOpen);
}

function updateThemeLabel() {
  const dictionary = translations[currentLanguage];
  const isDark = currentTheme === "dark";
  themeButton.setAttribute("aria-label", isDark ? dictionary.themeLight : dictionary.themeDark);
  themeButtonIcon.textContent = isDark ? "☀" : "☾";
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => {
    setLanguage(button.dataset.lang);
  });
});

menuButton.addEventListener("click", () => {
  const isOpen = mainNav.classList.toggle("is-open");
  document.body.classList.toggle("is-menu-open", isOpen);
  menuButton.setAttribute("aria-expanded", String(isOpen));
  updateMenuLabel();
});

themeButton.addEventListener("click", () => {
  setTheme(currentTheme === "dark" ? "light" : "dark");
});

navLinks.forEach((link) => {
  link.addEventListener("click", () => {
    closeMenu();
  });
});

setLanguage(currentLanguage);
setTheme(currentTheme);
